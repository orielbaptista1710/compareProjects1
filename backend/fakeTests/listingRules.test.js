// The API enforces the same listing rules as the form (FORM-04): the shared
// limits, minimum lengths and per-poster required fields in
// constants/listingRules.js, plus the form's number rules. A direct API call
// can't post what the form wouldn't let through, and an edit can't empty a
// required field. Each rejected field comes back with its reason (FORM-15).
import { describe, it, expect, beforeAll, afterAll, afterEach, vi } from "vitest";
import request from "supertest";
import * as backendRules from "../constants/listingRules.js";
import * as frontendRules from "../../frontend-vite/src/constants/listingRules.js";
import { LISTED_BY as BACKEND_LISTED_BY } from "../constants/roles.js";
import { LISTED_BY as FRONTEND_LISTED_BY } from "../../frontend-vite/src/constants/roles.js";

const { verifyIdToken } = vi.hoisted(() => ({ verifyIdToken: vi.fn() }));
vi.mock("../config/firebaseAdmin.js", () => ({
  default: { auth: () => ({ verifyIdToken }) },
}));

const { default: app } = await import("./helpers/roleSystemApp.js");
const { startTestDb, stopTestDb, clearTestDb } = await import("./helpers/db.js");
const { CONSENT, createCustomer, createUser, createProperty, signToken } = await import("./helpers/fixtures.js");
const { default: Property } = await import("../models/Property.js");

verifyIdToken.mockImplementation(async (token) => {
  if (!token.startsWith("token-for-")) {
    throw Object.assign(new Error("bad token"), { code: "auth/argument-error" });
  }
  return { uid: token.slice("token-for-".length) };
});

beforeAll(startTestDb);
afterAll(stopTestDb);
afterEach(clearTestDb);

// Everything an owner must fill in, as the form sends it
const OWNER_LISTING = {
  ...CONSENT,
  title: "2 BHK Flat in Andheri West, Mumbai", // generated by the form
  propertyType: "Flats/Apartments",
  description: "Sunny two bedroom flat near the station.",
  state: "Maharashtra",
  city: "Mumbai",
  locality: "Andheri West",
  address: "12 Test Road",
  pincode: "400053",
  price: 9500000,
  furnishing: "Unfurnished",
};
const AGENT_LISTING = { ...OWNER_LISTING, possessionStatus: "Ready to Move" };
const DEVELOPER_LISTING = { ...AGENT_LISTING, developerName: "Dev Co", unitsAvailable: 4 };

const bearer = (customer) => `Bearer token-for-${customer.firebaseUid}`;
const owner = () => createCustomer({ emailVerified: true });
const agent = () => createCustomer({ emailVerified: true, agent: { status: "approved" } });

const postAsCustomer = (customer, body) =>
  request(app).post("/api/customers/listings").set("Authorization", bearer(customer)).send(body);
const postAsDeveloper = async (body) =>
  request(app).post("/api/properties/add").set("Authorization", `Bearer ${signToken(await createUser())}`).send(body);
const without = (body, ...fields) => Object.fromEntries(Object.entries(body).filter(([k]) => !fields.includes(k)));

describe("the shared rules file", () => {
  it("is the same in the backend and the frontend", () => {
    expect(frontendRules).toEqual(backendRules);
    expect(FRONTEND_LISTED_BY).toEqual(BACKEND_LISTED_BY);
  });

  it("only lists fields the API accepts", async () => {
    const { propertyInputSchema } = await import("../validators/propertyInputValidator.js");
    const accepted = Object.keys(propertyInputSchema.shape);
    const named = [
      ...Object.keys(backendRules.TEXT_LIMITS),
      ...Object.keys(backendRules.TEXT_MINIMUMS),
      ...Object.values(backendRules.REQUIRED_FIELDS).flat(),
      ...Object.values(backendRules.FIELDS_NOT_FOR_TYPE).flat(),
      ...backendRules.LOCKED_AFTER_APPROVAL,
    ];
    expect(Object.keys(backendRules.FIELDS_NOT_FOR_TYPE).sort()).toEqual(
      propertyInputSchema.shape.propertyType.unwrap().options.slice().sort()
    );
    expect(named.filter((f) => !accepted.includes(f))).toEqual([]);
  });
});

describe("required fields per poster", () => {
  it("accepts each poster's complete listing", async () => {
    expect((await postAsCustomer(await owner(), OWNER_LISTING)).status).toBe(201);
    expect((await postAsCustomer(await agent(), AGENT_LISTING)).status).toBe(201);
    expect((await postAsDeveloper(DEVELOPER_LISTING)).status).toBe(201);
  });

  it("refuses an owner's listing without furnishing, naming the field", async () => {
    const res = await postAsCustomer(await owner(), without(OWNER_LISTING, "furnishing"));

    expect(res.status).toBe(400);
    expect(res.body.errors).toEqual({ furnishing: "This field is required" });
    expect(await Property.countDocuments()).toBe(0);
  });

  it("asks agents for possession status, but not owners", async () => {
    const res = await postAsCustomer(await agent(), OWNER_LISTING);

    expect(res.status).toBe(400);
    expect(res.body.errors).toEqual({ possessionStatus: "This field is required" });
  });

  it("asks developers for developer name, possession status and units", async () => {
    const res = await postAsDeveloper(OWNER_LISTING);

    expect(res.status).toBe(400);
    expect(Object.keys(res.body.errors).sort()).toEqual(["developerName", "possessionStatus", "unitsAvailable"]);
  });

  it("treats blank text as missing", async () => {
    const res = await postAsCustomer(await owner(), { ...OWNER_LISTING, city: "   " });

    expect(res.status).toBe(400);
    expect(res.body.errors).toHaveProperty("city");
  });
});

describe("the form's limits and number rules", () => {
  it.each([
    ["a description under 20 characters", { description: "Too short" }, "description", "Use at least 20 characters"],
    ["a description over 500 characters", { description: "x".repeat(501) }, "description", "Use 500 characters or fewer"],
    ["an address under 5 characters", { address: "1 A" }, "address", "Use at least 5 characters"],
    ["a price of 0", { price: 0 }, "price", "Price must be at least ₹1,00,000"],
    ["a price under ₹1 lakh", { price: 99999 }, "price", "Price must be at least ₹1,00,000"],
    ["a price over ₹1,000 crore", { price: 10000000001 }, "price", "Price must be at most ₹10,00,00,00,000"],
    ["a price in paise", { price: 9500000.5 }, "price", "Price must be in whole rupees"],
    ["an EMI in paise", { emiStarts: 45000.5 }, "emiStarts", "EMI must be in whole rupees"],
    ["an EMI over ₹1 crore", { emiStarts: 10000001 }, "emiStarts", "EMI must be at most ₹1,00,00,000"],
    ["an area under 10 sq ft", { area: { value: 5, unit: "sqft" } }, "area.value", expect.stringMatching(/check the unit/)],
    ["an area over 1 crore sq ft", { area: { value: 300, unit: "acres" } }, "area.value", expect.stringMatching(/check the unit/)],
    ["an unknown area type", { area: { value: 900, unit: "sqft", type: "balcony" } }, "area.type", "Pick carpet, built-up, super built-up or plot area"],
    ["21 bedrooms", { bhk: 21 }, "bhk", "Use 20 or fewer"],
    ["a 5-digit pincode", { pincode: "40005" }, "pincode", "Pincode must be exactly 6 digits"],
    ["a fractional BHK", { bhk: 2.5 }, "bhk", "Use a whole number"],
    ["0 total floors", { totalFloors: 0 }, "totalFloors", "Must be at least 1"],
    ["a fractional floor", { floor: 1.5 }, "floor", "Use a whole number"],
    ["a floor below B5", { floor: -6 }, "floor", "Lowest floor is B5"],
    ["a floor above the top floor", { floor: 11, totalFloors: 10 }, "floor", "The building has 10 floors"],
    ["a tower over 10 characters", { tower: "Tower Eleven" }, "tower", "Use 10 characters or fewer"],
  ])("refuses %s", async (_, change, field, reason) => {
    const res = await postAsCustomer(await owner(), { ...OWNER_LISTING, ...change });

    expect(res.status).toBe(400);
    expect(res.body.errors[field]).toEqual(reason);
  });

  it("refuses 0 units from a developer", async () => {
    const res = await postAsDeveloper({ ...DEVELOPER_LISTING, unitsAvailable: 0 });

    expect(res.status).toBe(400);
    expect(res.body.errors.unitsAvailable).toBe("Must be at least 1");
  });

  it("stores a basement floor and a lettered tower (FORM-18)", async () => {
    const res = await postAsCustomer(await owner(), { ...OWNER_LISTING, floor: -1, totalFloors: 10, tower: "T2" });

    expect(res.status).toBe(201);
    const saved = await Property.findOne().lean();
    expect(saved.floor).toBe(-1);
    expect(saved.tower).toBe("T2");
  });

  it("keeps a numeric tower from an older client as text", async () => {
    const res = await postAsCustomer(await owner(), { ...OWNER_LISTING, tower: 3 });

    expect(res.status).toBe(201);
    expect((await Property.findOne().lean()).tower).toBe("3");
  });

  it("accepts the price range's ends and stores the area type (FORM-06, FORM-07)", async () => {
    const customer = await owner();
    const low = await postAsCustomer(customer, { ...OWNER_LISTING, price: 100000 });
    const high = await postAsCustomer(customer, {
      ...OWNER_LISTING, address: "14 Test Road", price: 10000000000, area: { value: 2, unit: "acres", type: "plot" },
    });

    expect(low.status).toBe(201);
    expect(high.status).toBe(201);
    const saved = await Property.findById(high.body.property._id).lean();
    expect(saved.area).toEqual({ value: 2, unit: "acres", type: "plot" });
  });

  it("doesn't hold a developer-name minimum against an owner", async () => {
    const res = await postAsCustomer(await owner(), { ...OWNER_LISTING, developerName: "A" });

    expect(res.status).toBe(201);
  });
});

describe("edits", () => {
  const edit = (customer, listing, body) =>
    request(app).put(`/api/customers/listings/${listing._id}`).set("Authorization", bearer(customer)).send({ ...CONSENT, ...body });
  const ownerListing = (customer) =>
    createProperty({ userId: customer._id, ownerModel: "Customer", listedBy: "owner", developerName: undefined });

  it("can change one field without sending the rest", async () => {
    const customer = await owner();
    const listing = await ownerListing(customer);

    const res = await edit(customer, listing, { price: 8000000 });

    expect(res.status).toBe(200);
  });

  it("can't empty a required field", async () => {
    const customer = await owner();
    const listing = await ownerListing(customer);

    const res = await edit(customer, listing, { city: "", description: "   " });

    expect(res.status).toBe(400);
    expect(res.body.errors).toEqual({ city: "This field is required", description: "This field is required" });
    expect((await Property.findById(listing._id).lean()).city).toBe("Mumbai");
  });

  it("can't clear a required choice alongside another change", async () => {
    const customer = await owner();
    const listing = await ownerListing(customer);

    const res = await edit(customer, listing, { furnishing: "", price: 8000000 });

    expect(res.status).toBe(400);
    expect(res.body.errors).toEqual({ furnishing: "This field is required" });
    const after = await Property.findById(listing._id).lean();
    expect(after.furnishing).toBe("Unfurnished");
    expect(after.price).toBe(5000000);
  });

  it("checks a new floor against the saved total floors", async () => {
    const customer = await owner();
    const listing = await createProperty({
      userId: customer._id, ownerModel: "Customer", listedBy: "owner", developerName: undefined, totalFloors: 10,
      propertyType: "Flats/Apartments", // a villa has no unit floor (FORM-08)
    });

    const res = await edit(customer, listing, { floor: 12 });

    expect(res.status).toBe(400);
    expect(res.body.errors).toEqual({ floor: "The building has 10 floors" });
  });

  it("reads a tower saved as a number before it became text as unchanged", async () => {
    const customer = await owner();
    const listing = await ownerListing(customer);
    await Property.collection.updateOne({ _id: listing._id }, { $set: { tower: 3 } });

    const res = await edit(customer, listing, { tower: "3" });

    expect(res.status).toBe(200);
    expect(res.body.unchanged).toBe(true);
  });

  it("uses the rules of whoever posted the listing", async () => {
    // A developer listing saved before listedBy existed still needs a developer name
    const developer = await createUser();
    const listing = await createProperty({ userId: developer._id });
    await Property.collection.updateOne({ _id: listing._id }, { $unset: { listedBy: "" } });

    const res = await request(app)
      .put(`/api/properties/update/${listing._id}`)
      .set("Authorization", `Bearer ${signToken(developer)}`)
      .send({ ...CONSENT, developerName: "" });

    expect(res.status).toBe(400);
    expect(res.body.errors).toHaveProperty("developerName");
  });
});

describe("fields that follow the property type (FORM-08)", () => {
  const edit = (customer, listing, body) =>
    request(app).put(`/api/customers/listings/${listing._id}`).set("Authorization", bearer(customer)).send({ ...CONSENT, ...body });
  const PLOT = { ...without(OWNER_LISTING, "furnishing"), propertyType: "Plot", title: "Plot in Andheri West, Mumbai" };

  it("doesn't ask a plot for furnishing, and ignores bedrooms or floors sent for it", async () => {
    const res = await postAsCustomer(await owner(), {
      ...PLOT, bhk: 3, bathrooms: 2, floor: 4, totalFloors: 10, furnishing: "Furnished",
    });

    expect(res.status).toBe(201);
    const saved = await Property.findOne().lean();
    for (const field of ["bhk", "bathrooms", "floor", "totalFloors", "furnishing"]) {
      expect(saved).not.toHaveProperty(field);
    }
  });

  it("lets a shop leave furnishing out, but keeps it when given", async () => {
    const customer = await owner();
    const shop = { ...PLOT, propertyType: "Shop/Showroom", title: "Shop in Andheri West, Mumbai" };

    expect((await postAsCustomer(customer, shop)).status).toBe(201);
    const furnished = await postAsCustomer(customer, { ...shop, address: "14 Test Road", furnishing: "Furnished" });
    expect(furnished.status).toBe(201);
    expect(furnished.body.property.furnishing).toBe("Furnished");
  });

  it("still asks a villa for furnishing", async () => {
    const res = await postAsCustomer(await owner(), { ...PLOT, propertyType: "Villa" });

    expect(res.status).toBe(400);
    expect(res.body.errors).toEqual({ furnishing: "This field is required" });
  });

  it("clears a flat's bedrooms and floors when it becomes a plot", async () => {
    const customer = await owner();
    const created = await postAsCustomer(customer, { ...OWNER_LISTING, bhk: 2, floor: 3, totalFloors: 10 });

    const res = await edit(customer, created.body.property, { propertyType: "Plot" });

    expect(res.status).toBe(200);
    const saved = await Property.findById(created.body.property._id).lean();
    expect(saved.propertyType).toBe("Plot");
    for (const field of ["bhk", "floor", "totalFloors", "furnishing"]) {
      expect(saved).not.toHaveProperty(field);
    }
  });

  it("leaves an older plot's stored bedrooms alone, and counts sending them as no change", async () => {
    const customer = await owner();
    const listing = await createProperty({
      userId: customer._id, ownerModel: "Customer", listedBy: "owner", developerName: undefined, propertyType: "Plot",
    });
    await Property.collection.updateOne({ _id: listing._id }, { $set: { bhk: 3 } });

    const res = await edit(customer, listing, { bhk: 4 });

    expect(res.status).toBe(200);
    expect(res.body.unchanged).toBe(true);
    expect((await Property.findById(listing._id).lean()).bhk).toBe(3);
  });

  it("clears a saved area type when the poster removes it", async () => {
    const customer = await owner();
    const created = await postAsCustomer(customer, { ...OWNER_LISTING, area: { value: 900, unit: "sqft", type: "carpet" } });

    const res = await edit(customer, created.body.property, { area: { value: 900, unit: "sqft", type: "" } });

    expect(res.status).toBe(200);
    expect(res.body.unchanged).toBeUndefined();
    expect((await Property.findById(created.body.property._id).lean()).area).toEqual({ value: 900, unit: "sqft" });
  });

  it("counts an empty area type on a listing without one as no change", async () => {
    const customer = await owner();
    const created = await postAsCustomer(customer, { ...OWNER_LISTING, area: { value: 900, unit: "sqft" } });

    const res = await edit(customer, created.body.property, { area: { value: 900, unit: "sqft", type: "" } });

    expect(res.body.unchanged).toBe(true);
  });
});

describe("the map pin (FORM-10)", () => {
  const MUMBAI = { lat: 19.1197, lng: 72.8468 };
  const edit = (customer, listing, body) =>
    request(app).put(`/api/customers/listings/${listing._id}`).set("Authorization", bearer(customer)).send({ ...CONSENT, ...body });

  it("accepts a pin in India and stores it for map searches", async () => {
    const res = await postAsCustomer(await owner(), { ...OWNER_LISTING, coordinates: MUMBAI });

    expect(res.status).toBe(201);
    const saved = await Property.findOne().lean();
    expect(saved.geo.coordinates).toEqual([MUMBAI.lng, MUMBAI.lat]);
  });

  it.each([
    ["London", { lat: 51.5072, lng: -0.1276 }],
    ["Dubai", { lat: 25.2048, lng: 55.2708 }],
    ["0,0", { lat: 0, lng: 0 }],
  ])("refuses a pin in %s, on the pin field", async (_, coordinates) => {
    const res = await postAsCustomer(await owner(), { ...OWNER_LISTING, coordinates });

    expect(res.status).toBe(400);
    expect(res.body.errors).toEqual({ "coordinates.lat": "Place the pin inside India" });
    expect(await Property.countDocuments()).toBe(0);
  });

  it("ignores a removed pin on a new listing", async () => {
    const res = await postAsCustomer(await owner(), { ...OWNER_LISTING, coordinates: null });

    expect(res.status).toBe(201);
  });

  it("removes a saved pin, and its map point with it", async () => {
    const customer = await owner();
    const listing = await createProperty({
      userId: customer._id, ownerModel: "Customer", listedBy: "owner", coordinates: MUMBAI,
    });
    expect((await Property.findById(listing._id).lean()).geo.coordinates).toHaveLength(2);

    const res = await edit(customer, listing, { coordinates: null });

    expect(res.status).toBe(200);
    expect(res.body.unchanged).toBeUndefined();
    const after = await Property.findById(listing._id).lean();
    expect(after.coordinates?.lat).toBeUndefined();
    expect(after.coordinates?.lng).toBeUndefined();
    expect(after.geo?.coordinates ?? []).toEqual([]);
    expect(after.changedFields ?? []).not.toContain("geo");
  });

  it("treats removing a pin the listing never had as no change", async () => {
    const customer = await owner();
    const listing = await createProperty({ userId: customer._id, ownerModel: "Customer", listedBy: "owner" });

    const res = await edit(customer, listing, { coordinates: null });

    expect(res.status).toBe(200);
    expect(res.body.unchanged).toBe(true);
  });

  it("refuses moving a saved pin out of India and keeps the old one", async () => {
    const customer = await owner();
    const listing = await createProperty({
      userId: customer._id, ownerModel: "Customer", listedBy: "owner", coordinates: MUMBAI,
    });

    const res = await edit(customer, listing, { coordinates: { lat: 51.5, lng: -0.12 } });

    expect(res.status).toBe(400);
    expect((await Property.findById(listing._id).lean()).coordinates.lat).toBe(MUMBAI.lat);
  });
});

describe("consent to the terms and the accuracy of the details", () => {
  const edit = (customer, listing, body) =>
    request(app).put(`/api/customers/listings/${listing._id}`).set("Authorization", bearer(customer)).send(body);

  it("refuses a new listing without the two ticks", async () => {
    const customer = await owner();

    const res = await postAsCustomer(customer, without(OWNER_LISTING, "termsAccepted", "detailsConfirmed"));

    expect(res.status).toBe(400);
    expect(res.body.errors).toHaveProperty("termsAccepted");
    expect(res.body.errors).toHaveProperty("detailsConfirmed");
    expect(await Property.countDocuments()).toBe(0);
  });

  it("refuses a new listing when only one tick is given", async () => {
    const customer = await owner();

    const res = await postAsCustomer(customer, { ...OWNER_LISTING, detailsConfirmed: false });

    expect(res.status).toBe(400);
    expect(await Property.countDocuments()).toBe(0);
  });

  it("saves when and which terms were accepted, set by the server, and no tick fields", async () => {
    const customer = await owner();
    const before = Date.now();

    const res = await postAsCustomer(customer, OWNER_LISTING);

    expect(res.status).toBe(201);
    const saved = await Property.findOne().lean();
    expect(saved.consent.termsVersion).toBeTruthy();
    expect(saved.consent.termsAcceptedAt.getTime()).toBeGreaterThanOrEqual(before);
    expect(saved.consent.detailsConfirmedAt.getTime()).toBeGreaterThanOrEqual(before);
    expect(saved).not.toHaveProperty("termsAccepted");
    expect(saved).not.toHaveProperty("detailsConfirmed");
  });

  it("refuses a real edit without the ticks and keeps the old value", async () => {
    const customer = await owner();
    const listing = await createProperty({ userId: customer._id, ownerModel: "Customer", listedBy: "owner" });

    const res = await edit(customer, listing, { price: 8000000 });

    expect(res.status).toBe(400);
    expect(res.body.errors).toHaveProperty("termsAccepted");
    expect((await Property.findById(listing._id).lean()).price).not.toBe(8000000);
  });

  it("refuses an edit that sends a tick as false, even when nothing else changed", async () => {
    const customer = await owner();
    const listing = await createProperty({ userId: customer._id, ownerModel: "Customer", listedBy: "owner" });

    const res = await edit(customer, listing, { termsAccepted: false, price: 8000000 });

    expect(res.status).toBe(400);
    expect((await Property.findById(listing._id).lean()).price).not.toBe(8000000);
  });

  it("records fresh consent on a real edit", async () => {
    const customer = await owner();
    const listing = await createProperty({ userId: customer._id, ownerModel: "Customer", listedBy: "owner" });

    const res = await edit(customer, listing, { ...CONSENT, price: 8000000 });

    expect(res.status).toBe(200);
    const saved = await Property.findById(listing._id).lean();
    expect(saved.consent.termsAcceptedAt).toBeInstanceOf(Date);
  });

  it("doesn't ask for the ticks when nothing changed", async () => {
    const customer = await owner();
    const listing = await createProperty({ userId: customer._id, ownerModel: "Customer", listedBy: "owner" });

    const res = await edit(customer, listing, { price: listing.price });

    expect(res.status).toBe(200);
    expect(res.body.unchanged).toBe(true);
  });

  it("applies the same rule to developers on /api/properties/add", async () => {
    const res = await postAsDeveloper(without(DEVELOPER_LISTING, "termsAccepted", "detailsConfirmed"));

    expect(res.status).toBe(400);
    expect(res.body.errors).toHaveProperty("termsAccepted");
  });
});
